//! Stream-masked algorithm parameters for ADI provisioning.
//!
//! The byte arrays are copied in their masked storage form from the
//! MIT-licensed apple-auth reference and restored with the matching seed, the
//! same way the reference hides them from the binary image.

use std::sync::OnceLock;

/// xorshift32 byte stream used to unmask the stored tables.
struct Stream(u32);

impl Stream {
    fn next(&mut self) -> u32 {
        let mut value = self.0;
        value ^= value << 13;
        value ^= value >> 17;
        value ^= value << 5;
        self.0 = value;
        value
    }
}

pub(super) fn unmask_u8<const N: usize>(masked: &[u8; N], seed: u32) -> [u8; N] {
    let mut stream = Stream(seed);
    let mut output = *masked;
    for value in output.iter_mut() {
        *value ^= stream.next() as u8;
    }
    output
}

fn bytes_at<const N: usize>(source: &[u8], offset: usize) -> [u8; N] {
    std::array::from_fn(|index| source[offset + index])
}

