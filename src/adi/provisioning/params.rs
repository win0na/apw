struct Reader<'a> {
    bytes: &'a [u8],
    cursor: usize,
}

impl<'a> Reader<'a> {
    fn new(bytes: &'a [u8]) -> Self {
        Self { bytes, cursor: 0 }
    }

    fn byte(&mut self) -> u8 {
        let value = self.bytes[self.cursor];
        self.cursor += 1;
        value
    }

    fn array<const N: usize>(&mut self) -> [u8; N] {
        let value = bytes_at(self.bytes, self.cursor);
        self.cursor += N;
        value
    }

    fn response_key(&mut self) -> ResponseKey {
        let input_matrix_codecs = std::array::from_fn(|_| {
            // The stored matrix offset is unused by the decoder but still part
            // of the parameter stream.
            let _offset = self.byte();
            let basis_offset = self.array::<8>();
            let columns = std::array::from_fn(|_| MatrixColumn {
                source_byte: self.byte() as usize,
                row_mask: self.byte(),
                column_map: self.array::<8>(),
            });
            MatrixCodec {
                basis_offset,
                columns,
            }
        });
        ResponseKey {
            input_matrix_codecs,
            encoded_key_maps: std::array::from_fn(|_| self.array::<8>()),
            decoded_key_maps: std::array::from_fn(|_| self.array::<8>()),
            round_key_masks: self.array::<176>(),
        }
    }
}

// Offsets into the decoded 1020-byte request block.
const REQUEST_HARDWARE: usize = 48;
const REQUEST_SPIM_KEY: usize = REQUEST_HARDWARE + 272;
const REQUEST_RESPONSE_KEY: usize = REQUEST_SPIM_KEY + 32;
const REQUEST_HASH_SUFFIX: usize = REQUEST_RESPONSE_KEY + 596;
const REQUEST_DIGEST_KEY: usize = REQUEST_HASH_SUFFIX + 24;
const SELECTOR_SOURCE: usize = REQUEST_DIGEST_KEY + 16;

fn response_key(data: &[u8], offset: usize) -> ResponseKey {
    let mut reader = Reader::new(&data[offset..]);
    reader.response_key()
}

static REQUEST: OnceLock<RequestParameters> = OnceLock::new();
static END: OnceLock<EndParameters> = OnceLock::new();

pub(super) fn request() -> &'static RequestParameters {
    REQUEST.get_or_init(|| {
        let data = unmask_u8(&REQUEST_DATA, REQUEST_DATA_SEED);
        assert_eq!(SELECTOR_SOURCE + 32, data.len());
        RequestParameters {
            selector: SelectorCipher {
                key: bytes_at(&data, 0),
                iv: bytes_at(&data, 16),
                input_mask: bytes_at(&data, 32),
            },
            hardware: bytes_at(&data, REQUEST_HARDWARE),
            response: StartParameters {
                response: ResponseParameters {
                    spim: SpimCipher {
                        key: bytes_at(&data, REQUEST_SPIM_KEY),
                        iv: bytes_at(&data, REQUEST_SPIM_KEY + 16),
                    },
                    key: response_key(&data, REQUEST_RESPONSE_KEY),
                    hash_suffix: bytes_at(&data, REQUEST_HASH_SUFFIX),
                },
                digest_key: bytes_at(&data, REQUEST_DIGEST_KEY),
            },
        }
    })
}

pub(super) fn selector_source() -> SelectorSource {
    let data = unmask_u8(&REQUEST_DATA, REQUEST_DATA_SEED);
    let source = &data[SELECTOR_SOURCE..];
    SelectorSource {
        key: bytes_at(source, 0),
        iv: bytes_at(source, 16),
    }
}

pub(super) fn end() -> &'static EndParameters {
    END.get_or_init(|| {
        let data = unmask_u8(&END_DATA, END_DATA_SEED);
        const RESPONSE_KEY: usize = 32;
        const KEY_DERIVATION_KEY: usize = RESPONSE_KEY + 596;
        const AUTHENTICATION_KEY: usize = KEY_DERIVATION_KEY + 16;
        assert_eq!(AUTHENTICATION_KEY + 16, data.len());
        EndParameters {
            payload: EndPayloadParameters {
                spim: SpimCipher {
                    key: bytes_at(&data, 0),
                    iv: bytes_at(&data, 16),
                },
                response_key: response_key(&data, RESPONSE_KEY),
                key_derivation_key: bytes_at(&data, KEY_DERIVATION_KEY),
            },
            authentication_key: bytes_at(&data, AUTHENTICATION_KEY),
        }
    })
}
